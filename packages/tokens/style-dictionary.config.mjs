// Style Dictionary config for @mild-ui/tokens.
// Reads every token under src/{primitives,semantics,components} and writes:
//   - dist/tokens.css    CSS custom properties (--mild-*)
//   - dist/_tokens.scss  Sass variables ($mild-*, !default), importable by @mild-ui/core
//   - dist/tokens.json   the same values as a flat { "mild-x-y": value } map
//   - dist/tokens.ts     the same tree as the source JSON, as a typed `as const` object
//
// Run with: pnpm build (-> style-dictionary build --config style-dictionary.config.mjs)
import StyleDictionary from "style-dictionary";

const header = [
  "Do not edit directly, this file was auto-generated by @mild-ui/tokens.",
  "Source: src/primitives/, src/semantics/, src/components/.",
];

// Style Dictionary has no built-in TypeScript "as const" format: it ships `typescript/*` formats
// for ambient .d.ts declarations only, not for a runtime module. This walks the resolved tokens
// back into the same nested shape as the source JSON (instead of the dot/kebab names the other
// platforms use) and prints it as a `const` object literal.
StyleDictionary.registerFormat({
  name: "typescript/tokens-const",
  format: ({ dictionary }) => {
    const root = new Map();
    for (const token of dictionary.allTokens) {
      let node = root;
      for (const segment of token.path.slice(0, -1)) {
        if (!node.has(segment)) node.set(segment, new Map());
        node = node.get(segment);
      }
      node.set(token.path.at(-1), token.$value);
    }

    const serialize = (value, depth) => {
      const pad = "  ".repeat(depth);
      const childPad = "  ".repeat(depth + 1);
      if (value instanceof Map) {
        const lines = [...value].map(
          ([key, val]) =>
            `${childPad}${JSON.stringify(String(key))}: ${serialize(val, depth + 1)},`,
        );
        return `{\n${lines.join("\n")}\n${pad}}`;
      }
      if (Array.isArray(value)) {
        const oneLine = JSON.stringify(value);
        if (oneLine.length <= 80) return oneLine;
        const lines = value.map((item) => `${childPad}${JSON.stringify(item)},`);
        return `[\n${lines.join("\n")}\n${pad}]`;
      }
      return JSON.stringify(value);
    };

    const banner = header.map((line) => ` * ${line}`).join("\n");
    return (
      `/**\n${banner}\n */\n\n` +
      `export const tokens = ${serialize(root, 0)} as const;\n\n` +
      `export type MildTokens = typeof tokens;\n\n` +
      `export default tokens;\n`
    );
  },
});

/** @type {import("style-dictionary").Config} */
export default {
  source: [
    "src/primitives/**/*.json",
    // Only the shared semantic files. The per-theme files (light/dark/high-contrast.json) define
    // the same keys as each other and are not merged into this build; see README "Themes".
    "src/semantics/colors.json",
    "src/semantics/animation.json",
    "src/components/**/*.json",
  ],
  platforms: {
    css: {
      transformGroup: "css",
      prefix: "mild",
      buildPath: "dist/",
      files: [
        {
          destination: "tokens.css",
          format: "css/variables",
          options: { outputReferences: true },
        },
      ],
    },
    scss: {
      transformGroup: "scss",
      prefix: "mild",
      buildPath: "dist/",
      files: [
        {
          destination: "_tokens.scss",
          format: "scss/variables",
          options: { outputReferences: true, themeable: true },
        },
      ],
    },
    json: {
      transformGroup: "css",
      prefix: "mild",
      buildPath: "dist/",
      files: [{ destination: "tokens.json", format: "json/flat" }],
    },
    ts: {
      // Only needed so Style Dictionary gives every token a unique, collision-free `name`;
      // the format above ignores `name` and rebuilds the tree from each token's `path` instead.
      transforms: ["name/kebab"],
      buildPath: "dist/",
      files: [{ destination: "tokens.ts", format: "typescript/tokens-const" }],
    },
  },
};
